// Regenerates src/rules.js from tools/rules-src.js (+ keeps topics not defined there)
const fs = require('fs'), path = require('path');
const NEW = require('./rules-src.js');
const OLD = require('../src/rules.js').topics;
const ORDER = ['goal', 'day', 'city', 'actions', 'movement', 'police', 'notoriety', 'exec', 'contacts', 'business', 'safehouse', 'store', 'others', 'exits', 'assets', 'cards', 'howto', 'scoring', 'twop', 'solo', 'upgrade', 'tips', 'faq'];
const byId = {}; OLD.forEach(t => byId[t.id] = t); NEW.forEach(t => byId[t.id] = t);
const topics = ORDER.map(id => { if (!byId[id]) throw new Error('missing ' + id); return byId[id]; });
const src = fs.readFileSync(path.join(__dirname, '../src/rules.js'), 'utf8');
const tail = src.slice(src.indexOf('const R = { topics: T };'));
const out = `/* Heist — offline rules assistant: topics in EN/PT, searchable like a manual.\n   GENERATED by tools/rules-gen.js from tools/rules-src.js — edit there. */\n(function (root) {\n'use strict';\nconst T = ${JSON.stringify(topics, null, 1)};\n` + tail;
fs.writeFileSync(path.join(__dirname, '../src/rules.js'), out);
console.log('rules.js', topics.length, 'topics', out.length, 'bytes');
